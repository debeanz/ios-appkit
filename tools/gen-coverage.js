#!/usr/bin/env node
// Turns the gap-*.txt files from the import analysis into a coverage map:
// every macOS symbol the Steam client imports that iOS lacks, tagged with whether
// this shim implements it, stubs it, or hasn't touched it yet.
//
//   node gen-coverage.js <report-dir> <implemented.json> <out.md> <out.json>
//
// implemented.json lists what src/ actually provides, so the map can't drift from
// claims: { "classes": ["NSView", ...], "functions": ["NSBeep", ...],
//           "constants": ["NSAppearanceNameAqua", ...], "stubbed": ["NSSpellChecker", ...] }
'use strict';
const fs = require('fs');
const path = require('path');

const strip = s => s.replace(/^_/, '');
function kindOf(sym) {
  const s = strip(sym);
  if (s.startsWith('OBJC_CLASS_$_')) return ['class', s.slice('OBJC_CLASS_$_'.length)];
  if (s.startsWith('OBJC_METACLASS_$_')) return ['metaclass', s.slice('OBJC_METACLASS_$_'.length)];
  if (s.startsWith('OBJC_EHTYPE_$_')) return ['ehtype', s.slice('OBJC_EHTYPE_$_'.length)];
  // A leading-cap NS/CG/etc. name with no args is almost always a constant/global; the rest are functions.
  if (/^[A-Z]{2,}[A-Za-z0-9]+$/.test(s) && !/^(NSBeep|NSApp)/.test(s)) return ['constant', s];
  return ['function', s];
}

function main() {
  const [reportDir, implPath, outMd, outJson] = process.argv.slice(2);
  const impl = JSON.parse(fs.readFileSync(implPath, 'utf8'));
  const provided = {
    class: new Set(impl.classes || []),
    function: new Set(impl.functions || []),
    constant: new Set(impl.constants || []),
  };
  const stubbed = new Set(impl.stubbed || []); // class names we define but leave inert

  const frameworks = {};
  for (const file of fs.readdirSync(reportDir)) {
    const m = file.match(/^gap-(.+)\.txt$/);
    if (!m) continue;
    const fw = m[1];
    const rows = fs.readFileSync(path.join(reportDir, file), 'utf8').split('\n').filter(Boolean);
    const items = rows.map(line => {
      const [sym, users] = line.split('\t');
      const [kind, name] = kindOf(sym);
      let status = 'todo';
      if (kind === 'metaclass' || kind === 'ehtype') {
        // Implied by the class; counted as done when the class is implemented or stubbed.
        status = provided.class.has(name) ? 'implemented' : stubbed.has(name) ? 'stubbed' : 'todo';
      } else if (provided[kind] && provided[kind].has(name)) status = 'implemented';
      else if (kind === 'class' && stubbed.has(name)) status = 'stubbed';
      return { sym: strip(sym), kind, name, status, users: (users || '').split(', ').filter(Boolean).length };
    });
    frameworks[fw] = items;
  }

  const all = Object.values(frameworks).flat();
  const tally = s => all.filter(i => i.status === s).length;
  const summary = { total: all.length, implemented: tally('implemented'), stubbed: tally('stubbed'), todo: tally('todo') };

  let md = `# Coverage map\n\nGenerated by \`tools/gen-coverage.js\` from the import analysis. Do not edit by hand.\n\n`;
  md += `**${summary.implemented} implemented · ${summary.stubbed} stubbed · ${summary.todo} to do** of ${summary.total} missing symbols.\n\n`;
  md += `A symbol is "implemented" only when \`src/implemented.json\` lists it, so this map tracks real code, not intentions.\n\n`;
  md += `| Framework | Symbols | Implemented | Stubbed | To do |\n|---|--:|--:|--:|--:|\n`;
  for (const [fw, items] of Object.entries(frameworks).sort((a, b) => b[1].length - a[1].length)) {
    const t = s => items.filter(i => i.status === s).length;
    md += `| ${fw} | ${items.length} | ${t('implemented')} | ${t('stubbed')} | ${t('todo')} |\n`;
  }
  md += `\n## AppKit classes\n\n`;
  const classes = (frameworks.AppKit || []).filter(i => i.kind === 'class').sort((a, b) => b.users - a.users);
  md += `| Class | Imported by N binaries | Status |\n|---|--:|---|\n`;
  for (const c of classes) md += `| ${c.name} | ${c.users} | ${c.status} |\n`;

  fs.writeFileSync(outMd, md);
  fs.writeFileSync(outJson, JSON.stringify({ summary, frameworks }, null, 1));
  console.log(`${summary.implemented}/${summary.total} implemented, ${summary.stubbed} stubbed, ${summary.todo} to do`);
}
main();
