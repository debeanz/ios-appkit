#!/usr/bin/env node
// Coverage map: every system symbol the macOS Steam client imports that iOS doesn't export
// (data/ios-gap.json, produced by tools/ios-sdk-gap.js from the real iOS SDK), tagged with
// whether this shim implements it, stubs it, or hasn't touched it yet.
//
//   node tools/gen-coverage.js data/ios-gap.json src/implemented.json COVERAGE.md coverage.json
//
// If data/runtime-gap.json exists (tools/runtime-gap.m, run on a simulator), symbols it found
// at runtime are dropped: iOS has them after all, so the shim must not define them.
//
// implemented.json lists what src/ actually provides, so the map can't drift from claims:
// { "classes": [...], "functions": [...], "constants": [...], "stubbed": [...] }
'use strict';
const fs = require('fs');

const strip = s => s.replace(/^_/, '');
function kindOf(sym) {
  const s = strip(sym);
  if (s.startsWith('OBJC_CLASS_$_')) return ['class', s.slice('OBJC_CLASS_$_'.length)];
  if (s.startsWith('OBJC_METACLASS_$_')) return ['metaclass', s.slice('OBJC_METACLASS_$_'.length)];
  if (s.startsWith('OBJC_EHTYPE_$_')) return ['ehtype', s.slice('OBJC_EHTYPE_$_'.length)];
  return ['symbol', s];
}

function main() {
  const [gapPath, implPath, outMd, outJson] = process.argv.slice(2);
  const gap = JSON.parse(fs.readFileSync(gapPath, 'utf8'));
  const impl = JSON.parse(fs.readFileSync(implPath, 'utf8'));
  const classes = new Set(impl.classes || []);
  const symbols = new Set([...(impl.functions || []), ...(impl.constants || [])]);
  const stubbed = new Set(impl.stubbed || []);

  const runtimePath = require('path').join(require('path').dirname(gapPath), 'runtime-gap.json');
  const atRuntime = new Set();
  if (fs.existsSync(runtimePath)) {
    for (const lib of Object.values(JSON.parse(fs.readFileSync(runtimePath, 'utf8')).libraries))
      for (const s of lib.presentAtRuntime) atRuntime.add(s);
  }

  const frameworks = {};
  for (const info of Object.values(gap.libraries)) {
    const missing = info.missing.filter(s => !atRuntime.has(s));
    if (!missing.length) continue;
    frameworks[info.framework] = missing.map(sym => {
      const [kind, name] = kindOf(sym);
      let status = 'todo';
      if (kind === 'symbol') { if (symbols.has(name)) status = 'implemented'; }
      else if (classes.has(name)) status = 'implemented'; // metaclass/ehtype follow the class
      else if (stubbed.has(name)) status = 'stubbed';
      return { sym: strip(sym), kind, name, status };
    });
  }

  const all = Object.values(frameworks).flat();
  const tally = (items, s) => items.filter(i => i.status === s).length;
  const summary = { total: all.length, implemented: tally(all, 'implemented'), stubbed: tally(all, 'stubbed'), todo: tally(all, 'todo') };

  let md = `# Coverage map\n\nGenerated by \`tools/gen-coverage.js\`. Do not edit by hand.\n\n`;
  md += `The denominator is exact: every system symbol the macOS Steam client imports that the iOS SDK `;
  md += `(${gap.sdk.split('/').pop()}) does not export, from \`data/ios-gap.json\`. A symbol counts as `;
  md += `implemented only when \`src/implemented.json\` lists it, so this map tracks real code.`;
  md += atRuntime.size ? ` ${atRuntime.size} symbols the SDK lists as missing were found at runtime on a simulator (\`data/runtime-gap.json\`) and are left out.\n\n` : `\n\n`;
  md += `**${summary.implemented} implemented · ${summary.stubbed} stubbed · ${summary.todo} to do** of ${summary.total}.\n\n`;
  md += `| Framework | Missing on iOS | Implemented | Stubbed | To do |\n|---|--:|--:|--:|--:|\n`;
  for (const [fw, items] of Object.entries(frameworks).sort((a, b) => b[1].length - a[1].length)) {
    md += `| ${fw} | ${items.length} | ${tally(items, 'implemented')} | ${tally(items, 'stubbed')} | ${tally(items, 'todo')} |\n`;
  }
  for (const [fw, items] of Object.entries(frameworks).sort((a, b) => b[1].length - a[1].length)) {
    const todo = items.filter(i => i.status === 'todo' && i.kind !== 'metaclass' && i.kind !== 'ehtype').map(i => i.name);
    if (!todo.length) continue;
    md += `\n<details><summary>${fw}: ${todo.length} to do</summary>\n\n${todo.map(n => `\`${n}\``).join(' ')}\n\n</details>\n`;
  }

  fs.writeFileSync(outMd, md);
  fs.writeFileSync(outJson, JSON.stringify({ summary, frameworks }, null, 1));
  console.log(`${summary.implemented}/${summary.total} implemented, ${summary.stubbed} stubbed, ${summary.todo} to do`);
}
main();
