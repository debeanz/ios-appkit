#!/usr/bin/env node
// Writes the scripts the Safari-engine web helper injects into Steam's pages as C strings for
// WebHelperWeb.m:
//   src/WebHelperBridge.js -> src/WebHelperBridge.inc (kAKWHBridgeJS): the SteamClient bridge
//   src/WebHelperDeck.js   -> src/WebHelperDeck.inc   (kAKWHDeckJS): the Quick Access additions
//
//   node tools/gen-bridge.js
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
for (const [name, symbol] of [['WebHelperBridge', 'kAKWHBridgeJS'], ['WebHelperDeck', 'kAKWHDeckJS']]) {
  const js = fs.readFileSync(path.join(root, `src/${name}.js`), 'utf8');
  // Syntax check before it ships inside the app.
  new Function(js);
  const lines = js.split('\n').map((line) => '  "' + line.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '\\n"');
  const out = [
    `// Generated by tools/gen-bridge.js from src/${name}.js. Do not edit; rerun the generator.`,
    `static const char ${symbol}[] =`,
    ...lines,
    ';',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(root, `src/${name}.inc`), out);
  console.log(`wrote src/${name}.inc (${js.length} bytes of script)`);
}
