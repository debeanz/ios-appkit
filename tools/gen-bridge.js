#!/usr/bin/env node
// Writes src/WebHelperBridge.inc: src/WebHelperBridge.js (the SteamClient bridge the
// Safari-engine web helper injects into Steam's pages) as a C string for WebHelperWeb.m.
//
//   node tools/gen-bridge.js
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const js = fs.readFileSync(path.join(root, 'src/WebHelperBridge.js'), 'utf8');
// Syntax check before it ships inside the app.
new Function(js);
const lines = js.split('\n').map((line) => '  "' + line.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '\\n"');
const out = [
  '// Generated by tools/gen-bridge.js from src/WebHelperBridge.js. Do not edit; rerun the generator.',
  'static const char kAKWHBridgeJS[] =',
  ...lines,
  ';',
  '',
].join('\n');
fs.writeFileSync(path.join(root, 'src/WebHelperBridge.inc'), out);
console.log(`wrote src/WebHelperBridge.inc (${js.length} bytes of script)`);
