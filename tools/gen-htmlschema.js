#!/usr/bin/env node
// Writes src/HTMLSchema.inc: the protobuf schema of Steam's web-helper protocol as C tables,
// for the Safari-mode helper (WebHelper.m) to decode and encode Steam's commands.
//
//   node tools/gen-htmlschema.js
//
// Inputs (both recovered from Valve's binaries, see each file's header):
//   data/htmlmessages.proto  - the messages, rebuilt from the FileDescriptorProto Steam Helper
//                              embeds (field numbers, types, nesting)
//   data/htmlcommands.json   - eHTMLCommands value -> message, from the two dispatchers: the
//                              helper's (commands it receives) and chromehtml's (commands it
//                              receives); "guessed" entries come from the enum's alphabetical
//                              order and still need confirming on a device
// Types the .proto names but doesn't define (enums from enums.proto) are varint enums.
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const proto = fs.readFileSync(path.join(root, 'data/htmlmessages.proto'), 'utf8');
const commands = JSON.parse(fs.readFileSync(path.join(root, 'data/htmlcommands.json'), 'utf8'));

// Parse messages (with nesting) from the .proto text protodump.js wrote.
const messages = []; // { name (full, dotted), fields: [{label, type, name, number}] }
const stack = [];
for (const raw of proto.split('\n')) {
  const line = raw.trim();
  let m;
  if ((m = line.match(/^message (\w+) \{$/))) {
    const full = stack.length ? `${stack[stack.length - 1].name}.${m[1]}` : m[1];
    const msg = { name: full, fields: [] };
    messages.push(msg);
    stack.push(msg);
  } else if ((m = line.match(/^enum (\w+) \{$/))) {
    stack.push({ name: null, enumBlock: true });
  } else if (line === '}') {
    stack.pop();
  } else if ((m = line.match(/^(optional|required|repeated) ([\w.]+) (\w+) = (\d+);/)) && stack.length && !stack[stack.length - 1].enumBlock) {
    stack[stack.length - 1].fields.push({ label: m[1], type: m[2], name: m[3], number: Number(m[4]) });
  }
}
const byName = new Map(messages.map((msg, i) => [msg.name, i]));

const SCALAR = {
  double: 'AKPB_DOUBLE', float: 'AKPB_FLOAT', int32: 'AKPB_INT32', int64: 'AKPB_INT64',
  uint32: 'AKPB_UINT32', uint64: 'AKPB_UINT64', sint32: 'AKPB_SINT32', sint64: 'AKPB_SINT64',
  fixed32: 'AKPB_FIXED32', fixed64: 'AKPB_FIXED64', sfixed32: 'AKPB_SFIXED32', sfixed64: 'AKPB_SFIXED64',
  bool: 'AKPB_BOOL', string: 'AKPB_STRING', bytes: 'AKPB_BYTES',
};

// A field type name resolves like protobuf scoping: innermost enclosing message first.
function resolve(type, scope) {
  const parts = scope.split('.');
  for (let i = parts.length; i >= 0; i--) {
    const candidate = [...parts.slice(0, i), type].join('.');
    if (byName.has(candidate)) return byName.get(candidate);
  }
  return -1;
}

const ident = (name) => name.replace(/\./g, '_');
const out = [];
out.push('// Generated by tools/gen-htmlschema.js from data/htmlmessages.proto and data/htmlcommands.json.');
out.push('// Do not edit; rerun the generator.');
out.push('');
for (const msg of messages) {
  if (!msg.fields.length) continue;
  out.push(`static const AKPBField kAKPBFields_${ident(msg.name)}[] = {`);
  for (const f of msg.fields) {
    let type = SCALAR[f.type], sub = -1;
    if (!type) {
      sub = resolve(f.type, msg.name);
      type = sub >= 0 ? 'AKPB_MESSAGE' : 'AKPB_ENUM';
    }
    out.push(`  { ${f.number}, "${f.name}", ${type}, ${f.label === 'repeated' ? 1 : 0}, ${sub} },`);
  }
  out.push('};');
}
out.push('');
out.push(`#define AKPB_MESSAGE_COUNT ${messages.length}`);
out.push('static const AKPBMessage kAKPBMessages[AKPB_MESSAGE_COUNT] = {');
for (const msg of messages) {
  out.push(msg.fields.length
    ? `  { "${msg.name}", kAKPBFields_${ident(msg.name)}, ${msg.fields.length} },`
    : `  { "${msg.name}", NULL, 0 },`);
}
out.push('};');
out.push('');
out.push('// eHTMLCommands: value, name, message index (-1: none known), who receives it');
out.push('// (AKHTML_TO_HELPER, AKHTML_TO_CLIENT or both), and whether the mapping is inferred.');
out.push('static const AKHTMLCommandInfo kAKHTMLCommands[] = {');
for (const [id, c] of Object.entries(commands)) {
  const idx = c.message ? byName.get(c.message) : -1;
  if (c.message && idx === undefined) throw new Error(`command ${id}: no message ${c.message}`);
  const to = c.to === 'both' ? 'AKHTML_TO_HELPER | AKHTML_TO_CLIENT' : c.to === 'helper' ? 'AKHTML_TO_HELPER' : 'AKHTML_TO_CLIENT';
  out.push(`  { ${id}, "${c.name || `Command${id}`}", ${idx ?? -1}, ${to}, ${c.guessed ? 1 : 0} },`);
}
out.push('};');
fs.writeFileSync(path.join(root, 'src/HTMLSchema.inc'), out.join('\n') + '\n');
console.log(`wrote src/HTMLSchema.inc: ${messages.length} messages, ${Object.keys(commands).length} commands`);
